//go:build linux

package system

import (
	"fmt"
	"net/netip"
	"os"
	"path/filepath"
	"strings"
)

func renderResolvConf(dns []netip.Addr) (string, error) {
	if len(dns) == 0 {
		return "", ErrDHCPDNSUnavailable
	}
	var b strings.Builder
	b.WriteString("# Generated by VeriRelay DHCPv4 initialization.\n")
	for i, server := range dns {
		if i == maxDNSServers {
			break
		}
		if !validUnicastIPv4(server) {
			return "", fmt.Errorf("%w: invalid DNS %s", ErrInvalidDHCPLease, server)
		}
		b.WriteString("nameserver ")
		b.WriteString(server.String())
		b.WriteByte('\n')
	}
	b.WriteString("options timeout:2 attempts:2\n")
	return b.String(), nil
}

func writeResolvConf(path string, dns []netip.Addr) error {
	if path == "" {
		path = "/etc/resolv.conf"
	}
	content, err := renderResolvConf(dns)
	if err != nil {
		return err
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // G301: PID 1 in the initrd creates /etc for resolv.conf; it must be 0755
		return fmt.Errorf("create resolv.conf directory: %w", err)
	}

	tmp, err := os.CreateTemp(dir, ".resolv.conf.*")
	if err != nil {
		return fmt.Errorf("create temporary resolv.conf: %w", err)
	}
	tmpName := tmp.Name()
	defer func() { _ = os.Remove(tmpName) }()

	if _, err := tmp.WriteString(content); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("write temporary resolv.conf: %w", err)
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("sync temporary resolv.conf: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close temporary resolv.conf: %w", err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		return fmt.Errorf("replace resolv.conf: %w", err)
	}
	if dirFile, err := os.Open(dir); err == nil {
		_ = dirFile.Sync()
		_ = dirFile.Close()
	}
	return nil
}
